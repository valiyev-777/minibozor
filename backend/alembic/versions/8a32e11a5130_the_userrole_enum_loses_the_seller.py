"""the userrole enum loses the seller

`UserRole.SELLER` is deleted from the application: there is one shop, and the
person who photographs the goods is the person who sells them, so everything
the role guarded — the shop window, the order queue, the dashboard — is the
admin's now. A value the code no longer names must come out of the database
type too, or the next `sa.Enum` autogenerate diff will disagree with the
server for ever.

**Postgres cannot drop an enum value.** `3b4d3d7fc68b` added `'SELLER'` with
`ADD VALUE` and documented that the road back is a type rebuild; this is that
rebuild, done deliberately rather than in a rollback. The order matters:

1. any row still holding `'SELLER'` is moved to `'ADMIN'` first — in this
   shop the seller's work was always the owner's work, and a cast with the
   value still present would abort the whole migration;
2. the old type is renamed aside, a new `userrole` is created without the
   value, and both columns that use it — `users.role` and
   `audit_log.actor_role` — are rewritten onto it through a text cast;
3. the old type is dropped.

The rewrite takes an exclusive lock on both tables; they are small here and
the alternative is a phantom value in every future schema comparison.

**A no-op on SQLite**, where an enum column is a plain VARCHAR with no
server-side value list — the same dialect guard `3b4d3d7fc68b` used. The row
rewrite of step 1 still runs there: SQLite will happily keep holding a value
the application can no longer read, and one such row would sign in as a 500.

The skeleton was autogenerated for the id/down_revision wiring; the enum
surgery is explicit `op.execute`, because there is no `op.*` operation for
rebuilding a Postgres enum and autogenerate cannot see server-side types on
the SQLite database development runs against.

Revision ID: 8a32e11a5130
Revises: 3b4d3d7fc68b
Create Date: 2026-09-14 16:21:26.680694

"""
