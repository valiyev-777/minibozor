def upgrade() -> None:
    """Move any seller to admin, then rebuild `userrole` without SELLER."""
    bind = op.get_bind()

    # The rows first, on every dialect: the enum member is gone from the code,
    # so a row holding it is unreadable whatever the column type is. Stored by
    # *name* — SQLAlchemy maps a Python enum by name, so the rows say 'SELLER'.
    op.execute("UPDATE users SET role = 'ADMIN' WHERE role = 'SELLER'")
    op.execute(
        "UPDATE audit_log SET actor_role = 'ADMIN' WHERE actor_role = 'SELLER'"
    )

    if bind.dialect.name != "postgresql":
        # SQLite stores the column as text; there is no server-side value
        # list to rebuild.
        return

    # There is no ALTER TYPE ... DROP VALUE: build the four-value type the
    # baseline had, swing both columns over, drop the five-value one.
    op.execute("ALTER TYPE userrole RENAME TO userrole_old")
    op.execute(
        "CREATE TYPE userrole AS ENUM ('CUSTOMER', 'ADMIN', 'WAREHOUSE', 'COURIER')"
    )
    op.execute(
        "ALTER TABLE users ALTER COLUMN role "
        "TYPE userrole USING role::text::userrole"
    )
    op.execute(
        "ALTER TABLE audit_log ALTER COLUMN actor_role "
        "TYPE userrole USING actor_role::text::userrole"
    )
    op.execute("DROP TYPE userrole_old")


def downgrade() -> None:
    """Put the value back, the way `3b4d3d7fc68b` first added it.

    The accounts that were moved to admin stay admin: which users held the
    role is information the upgrade deliberately spent, and inventing sellers
    on the way down would be worse than having none.
    """
    bind = op.get_bind()
    if bind.dialect.name != "postgresql":
        return

    # Alembic opened a transaction; before Postgres 12, ADD VALUE refuses to
    # run inside one. Committing here ends Alembic's transaction — safe,
    # because this downgrade does exactly one thing.
    op.execute("COMMIT")
    op.execute("ALTER TYPE userrole ADD VALUE IF NOT EXISTS 'SELLER'")
